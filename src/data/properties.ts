import { Property } from '../types/property';
import { NXZ_PROJECTS, NXZProject } from './nxzProjects';

// Convert NXZ projects exclusively sourced from https://nxzdigital.com into Property models
export const INITIAL_PROPERTIES: Property[] = NXZ_PROJECTS.map((p: NXZProject) => ({
  id: p.slug,
  slug: p.slug,
  name: p.name,
  tagline: p.tagline,
  developerName: p.developerName,
  location: p.location,
  specificAddress: p.specificAddress,
  propertyType: p.propertyType,
  configurations: p.configurations,
  startingPrice: p.startingPrice,
  priceNumeric: p.priceNumeric,
  areaRange: p.areaRange,
  statusBadge: p.statusBadge,
  statusType: p.statusType,
  isDetailed: true,
  isFeatured: p.isFeatured,
  image: p.image,
  gallery: p.gallery,
  headline: `${p.name} — Exclusive Luxury Living in ${p.location}`,
  description: p.description,
  reraNumber: p.reraNumber,
  possessionYear: p.statusBadge === 'Ready to Move' ? 'Ready to Move' : '2026 – 2028',
  keyHighlights: p.projectHighlights,
  projectHighlights: p.projectHighlights,
  locationHighlights: p.locationHighlights,
  nearbyLocations: p.nearbyLocations,
  locationFeatures: p.locationFeatures,
  amenitiesList: p.amenities,
  amenities: p.amenities.map((a: string) => ({ name: a, category: 'Lifestyle' })),
  floorPlanRows: p.floorPlanRows,
  avgPricePerSqFt: p.avgPricePerSqFt,
  carpetAreaRange: p.carpetAreaRange,
  planDiagrams: p.planDiagrams,
  driveDocuments: p.driveDocuments,
  keySpecs: [
    { label: 'Project Status', value: p.statusBadge },
    { label: 'Configurations', value: p.configurations.join(', ') },
    { label: 'Sizes / Built-up', value: p.areaRange },
    { label: 'Carpet Area', value: p.carpetAreaRange || 'Varies by plan' },
    { label: 'Avg Rate per SFT', value: p.avgPricePerSqFt || 'Competitive' },
    { label: 'Location Corridor', value: p.location },
    { label: 'TS RERA Registration', value: p.reraNumber || 'Verified' },
    { label: 'Developer', value: p.developerName },
  ],
}));
